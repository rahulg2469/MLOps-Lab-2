
# WHAT CHANGED compared to the original lab
# -------------------------------------------
# 1. Data: the synthetic make_classification data (with a random 0-2000 rows,
#    which could be 0 and crash) is replaced by the Breast Cancer train split
#    from dataset.py. 
# 2. Model: RandomForestClassifier is replaced by GradientBoostingClassifier.
# 3. Training metrics removed: the original scored the model on the same
#    data it trained on. Scoring now happens in evaluate_model.py on a
#    held-out test set.
# 4. MLflow removed: the original logged to a local ./mlruns folder that was
#    never committed or viewed. Metrics now go to metrics/*.json and to the
#    GitHub Actions run summary (see evaluate_model.py).
# 5. Model is saved straight into models/ (the original saved it to the
#    current folder and the workflow had to mv it). File name changed from
#    model_<ts>_dt_model.joblib to model_<ts>_gb.joblib ("dt" was wrong; it
#    was never a decision tree).
# 6. New --search-seed option, used by the nightly workflow. When given, the
#    script picks a random hyperparameter config from SEARCH_SPACE instead of
#    the defaults. The nightly workflow then keeps the new model only if it
#    beats the current one.
# =============================================================================

import argparse
import os
import random

from joblib import dump
from sklearn.ensemble import GradientBoostingClassifier

from dataset import load_splits

DEFAULT_PARAMS = {"n_estimators": 100, "learning_rate": 0.1, "max_depth": 3}

# Small grid the nightly workflow samples one config from
SEARCH_SPACE = {
    "n_estimators": [50, 100, 200, 300],
    "learning_rate": [0.03, 0.05, 0.1, 0.2],
    "max_depth": [2, 3, 4],
}


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--timestamp", type=str, required=True,
                        help="Version id for this model, generated by GitHub Actions")
    parser.add_argument("--search-seed", type=int, default=None,
                        help="If set, pick a random hyperparameter config from SEARCH_SPACE")
    args = parser.parse_args()

    if args.search_seed is None:
        params = DEFAULT_PARAMS
    else:
        rng = random.Random(args.search_seed)
        params = {name: rng.choice(values) for name, values in SEARCH_SPACE.items()}

    print(f"Timestamp: {args.timestamp}")
    print(f"Hyperparameters: {params}")

    # Only the train split is used here; calibration and test rows stay unseen
    X_train, _, _, y_train, _, _ = load_splits()
    model = GradientBoostingClassifier(random_state=0, **params)
    model.fit(X_train, y_train)

    os.makedirs("models", exist_ok=True)
    model_path = f"models/model_{args.timestamp}_gb.joblib"
    dump(model, model_path)
    print(f"Saved trained model to {model_path}")